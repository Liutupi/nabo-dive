def fixed(im,palette):
 colors=[tuple(bytes.fromhex(c[1:])) for c in palette]
 pal=Image.new('P',(1,1));pal.putpalette([v for c in colors+[colors[-1]]*(256-len(colors)) for v in c])
 rgb=im.convert('RGB').quantize(palette=pal,dither=Image.Dither.NONE).convert('RGB')
 rgb.putalpha(Image.fromarray((np.round(np.asarray(im.getchannel('A'),dtype=float)/17)*17).astype('uint8')))
 return rgb

